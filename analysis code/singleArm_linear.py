for idx, (arm_name, data) in enumerate(arm_info.items()):
    ax = axes[idx]
    dist, area, target_info = analyze_arm(arm_name, data, start_points[arm_name])
    all_arm_details[arm_name] = (dist, area, target_info)

    # Scatter using exact distances (no jitter)
    ax.scatter(dist, area, c=colors[arm_name], marker=markers[arm_name],
               s=80, edgecolors='k', alpha=0.8, zorder=5)

    # Add labels showing target coordinates
    for i, ((tx, ty), d, a) in enumerate(target_info):
        label = f"({tx},{ty})"
        ax.annotate(label, (dist[i], area[i]),
                    textcoords="offset points", xytext=(5,5),
                    fontsize=7, alpha=0.9,
                    arrowprops=dict(arrowstyle="-", color='grey', lw=0.5))

    # Linear fit (using original distances)
    if len(dist) > 1:
        coeffs = np.polyfit(dist, area, 1)
        x_line = np.linspace(dist.min(), dist.max(), 50)
        y_line = np.polyval(coeffs, x_line)
        corr = np.corrcoef(dist, area)[0, 1]
        ax.plot(x_line, y_line, '--', color=colors[arm_name], linewidth=2,
                label=f'Fit: slope={coeffs[0]:.3f}\nR²={corr**2:.3f}')

    ax.set_xlabel('Distance from start to target (units)')
    ax.set_ylabel('Cluster area (units²)')
    ax.set_title(f'{arm_name}')
    ax.grid(True, linestyle='--', alpha=0.5)
    ax.legend()

