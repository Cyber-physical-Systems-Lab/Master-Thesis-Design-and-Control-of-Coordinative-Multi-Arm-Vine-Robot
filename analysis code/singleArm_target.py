# Plotting function with target labels added
def plot_arm(arm_data, arm_name, start_point, color_target='red', color_actual='blue', alpha=0.6):
    if not arm_data:
        print(f"No data for {arm_name}")
        return

    target_x = [d[0] for d in arm_data]
    target_y = [d[1] for d in arm_data]
    actual_x = [d[2] for d in arm_data]
    actual_y = [d[3] for d in arm_data]

    # combine to compute axis limits
    all_x = target_x + actual_x + [start_point[0]]
    all_y = target_y + actual_y + [start_point[1]]
    min_x, max_x = min(all_x), max(all_x)
    min_y, max_y = min(all_y), max(all_y)
    dx = (max_x - min_x) * 0.05 + 0.5
    dy = (max_y - min_y) * 0.05 + 0.5

    plt.figure(figsize=(8, 8))
    ax = plt.gca()

    # Plot start point
    ax.scatter(start_point[0], start_point[1], c='green', marker='s', s=100,
               label='Start point', edgecolors='k', zorder=5)
    # Plot targets
    ax.scatter(target_x, target_y, c=color_target, marker='o', s=50,
               label='Target', alpha=alpha, edgecolors='k')
    # Plot actual reaches
    ax.scatter(actual_x, actual_y, c=color_actual, marker='x', s=50,
               label='Actual reach', alpha=alpha)

    # Connect each target to its actual point
    for i in range(len(arm_data)):
        ax.plot([target_x[i], actual_x[i]], [target_y[i], actual_y[i]],
                'k-', linewidth=0.5, alpha=0.3)

    # -------- Label unique targets ----------
    unique_targets = set((d[0], d[1]) for d in arm_data)
    for tx, ty in unique_targets:
        ax.annotate(f"({tx},{ty})", (tx, ty),
                    textcoords="offset points", xytext=(5,5),
                    fontsize=8, color='darkred', alpha=0.9,
                    fontweight='bold',
                    bbox=dict(boxstyle='round,pad=0.2', facecolor='white', alpha=0.7))

    ax.set_xlabel('X coordinate')
    ax.set_ylabel('Y coordinate')
    ax.set_title(f'{arm_name} – Target vs Actual Reach (Start: {start_point})')
    ax.legend()
    ax.grid(True, linestyle='--', alpha=0.5)
    ax.axis('equal')

    # Ticks at every integer
    ax.xaxis.set_major_locator(MultipleLocator(1))
    ax.yaxis.set_major_locator(MultipleLocator(1))

    ax.set_xlim(min_x - dx, max_x + dx)
    ax.set_ylim(min_y - dy, max_y + dy)

    plt.tight_layout()
    plt.show()

# Define start points
